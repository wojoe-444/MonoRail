const { test, describe } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

const { openDatabase } = require('../../localdb/index.cjs')
const { createTracker, OWN_TYPES } = require('./model.cjs')
const { SCOPES } = require('../../profiles/index.cjs')
const STANDARD = require('../../../src/standard/standard.json')

let clock = Date.parse('2026-11-18T12:00:00Z')
const fresh = () => {
  const db = openDatabase(fs.mkdtempSync(path.join(os.tmpdir(), 'monorail-tracker-')))
  return { db, t: createTracker(db, { now: () => clock++ }) }
}
const stateOf = (snap, teamId, name) => snap.states.find((s) => s.teamId === teamId && s.name === name)

describe('tracker', () => {
  test('is declared: data folder scope and every entity type in the standard', () => {
    assert.equal(SCOPES['apps/tracker'], 'profile')
    const types = new Set(STANDARD.entities.map((e) => e.type))
    for (const t of [...OWN_TYPES, 'team', 'user']) assert.ok(types.has(t), `${t} is in standard.json`)
    for (const t of OWN_TYPES) assert.equal(STANDARD.entities.find((e) => e.type === t).category, 'tracker')
  })

  test('a new team gets the default workflow, a default status and a member for you', () => {
    const { t } = fresh()
    const team = t.createTeam({ name: 'Engineering', key: 'eng' })
    assert.equal(team.key, 'ENG')
    const snap = t.snapshot()
    assert.deepEqual(snap.states.filter((s) => s.teamId === team.id).sort((a, b) => a.position - b.position).map((s) => s.type), ['triage', 'backlog', 'unstarted', 'started', 'started', 'completed', 'canceled', 'canceled'])
    assert.equal(team.defaultStateId, stateOf(snap, team.id, 'Todo').id)
    assert.ok(snap.meId)
    assert.throws(() => t.createTeam({ name: 'Other', key: 'ENG' }), /already uses that key/)
    assert.throws(() => t.createTeam({ name: 'Bad', key: '1X' }), /starts with a letter/)
  })

  test('issues get numbers per team, status time stamps and a history from versions', () => {
    const { t } = fresh()
    const team = t.createTeam({ name: 'Engineering', key: 'ENG', estimateType: 'linear' })
    const a = t.createIssue({ teamId: team.id, title: 'First', priority: 2, estimate: 3 })
    const b = t.createIssue({ teamId: team.id, title: 'Second' })
    assert.deepEqual([a.number, b.number], [1, 2])
    assert.equal(a.stateId, team.defaultStateId)
    const started = stateOf(t.snapshot(), team.id, 'In Progress')
    const done = stateOf(t.snapshot(), team.id, 'Done')
    const [s] = t.updateIssues({ ids: [a.id], patch: { stateId: started.id } })
    assert.ok(s.startedAt)
    const [d] = t.updateIssues({ ids: [a.id], patch: { stateId: done.id, title: 'First, renamed' } })
    assert.ok(d.completedAt)
    const { history } = t.issueDetail({ id: a.id })
    assert.deepEqual(history.map((h) => h.field).sort(), ['stateId', 'stateId', 'title'])
    assert.throws(() => t.createIssue({ teamId: team.id, title: '' }), /title is required/)
    assert.throws(() => t.createIssue({ teamId: team.id, title: 'x', priority: 9 }), /priority/)
  })

  test('parents cannot loop, labels allow one per group, milestones follow their project', () => {
    const { t } = fresh()
    const team = t.createTeam({ name: 'Eng', key: 'ENG' })
    const parent = t.createIssue({ teamId: team.id, title: 'Parent' })
    const child = t.createIssue({ teamId: team.id, title: 'Child', parentId: parent.id })
    assert.throws(() => t.updateIssues({ ids: [parent.id], patch: { parentId: child.id } }), /own parent/)
    const group = t.save({ type: 'issueLabel', entity: { name: 'Type', isGroup: true } })
    const bug = t.save({ type: 'issueLabel', entity: { name: 'Bug', parentId: group.id } })
    const feat = t.save({ type: 'issueLabel', entity: { name: 'Feature', parentId: group.id } })
    assert.throws(() => t.updateIssues({ ids: [child.id], patch: { labelIds: [bug.id, feat.id] } }), /one label from each group/)
    const [swapped] = t.updateIssues({ ids: [child.id], addLabelIds: [feat.id] })
    assert.deepEqual(swapped.labelIds, [feat.id])
    assert.deepEqual(t.updateIssues({ ids: [child.id], addLabelIds: [bug.id] })[0].labelIds, [bug.id], 'adding a label replaces its group sibling')
    const p1 = t.save({ type: 'project', entity: { name: 'One' } })
    const p2 = t.save({ type: 'project', entity: { name: 'Two' } })
    const m = t.save({ type: 'projectMilestone', entity: { projectId: p1.id, name: 'Beta' } })
    t.updateIssues({ ids: [child.id], patch: { projectId: p1.id, projectMilestoneId: m.id } })
    assert.throws(() => t.updateIssues({ ids: [child.id], patch: { projectId: p2.id, projectMilestoneId: m.id } }), /another project/)
    assert.equal(t.updateIssues({ ids: [child.id], patch: { projectId: p2.id } })[0].projectMilestoneId, null, 'changing project clears the milestone')
    assert.throws(() => t.save({ type: 'project', entity: { name: 'One' } }), /already a project/)
  })

  test('moving an issue to another team gives it a new number and the same kind of status', () => {
    const { t } = fresh()
    const a = t.createTeam({ name: 'A', key: 'A' })
    const b = t.createTeam({ name: 'B', key: 'B' })
    const i = t.createIssue({ teamId: a.id, title: 'Move me', stateId: stateOf(t.snapshot(), a.id, 'In Review').id })
    const [moved] = t.updateIssues({ ids: [i.id], patch: { teamId: b.id } })
    assert.equal(moved.number, 1)
    assert.deepEqual(moved.previousIdentifiers, ['A-1'])
    assert.equal(t.snapshot().states.find((s) => s.id === moved.stateId).type, 'started')
  })

  test('removing things clears references; issues are deleted softly and come back', () => {
    const { t } = fresh()
    const team = t.createTeam({ name: 'Eng', key: 'ENG', triageEnabled: true })
    const p = t.save({ type: 'project', entity: { name: 'Proj' } })
    const label = t.save({ type: 'issueLabel', entity: { name: 'Bug', teamId: team.id } })
    const i = t.createIssue({ teamId: team.id, title: 'x', projectId: p.id, labelIds: [label.id] })
    t.save({ type: 'comment', entity: { issueId: i.id, body: 'Hello' } })
    assert.equal(t.snapshot().commentCounts[i.id], 1)
    t.remove({ type: 'project', id: p.id })
    t.remove({ type: 'issueLabel', id: label.id })
    let got = t.snapshot().issues.find((x) => x.id === i.id)
    assert.equal(got.projectId, null)
    assert.deepEqual(got.labelIds, [])
    t.deleteIssues({ ids: [i.id] })
    assert.equal(t.snapshot().issues.length, 0)
    assert.throws(() => t.remove({ type: 'team', id: team.id }), /issues first/)
    t.restoreIssues({ ids: [i.id] })
    got = t.snapshot().issues.find((x) => x.id === i.id)
    assert.ok(got && !got.deleted)
    const todo = stateOf(t.snapshot(), team.id, 'Todo')
    assert.throws(() => t.remove({ type: 'workflowState', id: todo.id }), /default status/)
    const review = stateOf(t.snapshot(), team.id, 'In Review')
    t.updateIssues({ ids: [i.id], patch: { stateId: review.id } })
    assert.throws(() => t.remove({ type: 'workflowState', id: review.id }), /another status/)
    t.remove({ type: 'workflowState', id: review.id, moveTo: stateOf(t.snapshot(), team.id, 'In Progress').id })
    assert.equal(t.snapshot().issues[0].stateId, stateOf(t.snapshot(), team.id, 'In Progress').id)
  })

  test('project removal clears project and milestone from restorable issues', () => {
    const { db, t } = fresh()
    const team = t.createTeam({ name: 'Engineering', key: 'ENG' })
    const project = t.save({ type: 'project', entity: { name: 'Example project' } })
    const milestone = t.save({ type: 'projectMilestone', entity: { name: 'First milestone', projectId: project.id } })
    const issue = t.createIssue({ teamId: team.id, title: 'Example issue', projectId: project.id, projectMilestoneId: milestone.id })
    t.deleteIssues({ ids: [issue.id] })
    t.remove({ type: 'project', id: project.id })
    assert.equal(db.byId(issue.id).deleted, true)
    assert.equal(db.byId(issue.id).projectId, null)
    assert.equal(db.byId(issue.id).projectMilestoneId, null)
    t.restoreIssues({ ids: [issue.id] })
    assert.equal(t.updateIssues({ ids: [issue.id], patch: { title: 'Edited' } })[0].title, 'Edited')
  })

  test('Undo repairs optional references already left dangling in storage', () => {
    const { db, t } = fresh()
    const team = t.createTeam({ name: 'Engineering', key: 'ENG' })
    const project = t.save({ type: 'project', entity: { name: 'Example project' } })
    const milestone = t.save({ type: 'projectMilestone', entity: { name: 'First milestone', projectId: project.id } })
    const parent = t.createIssue({ teamId: team.id, title: 'Parent' })
    const label = t.save({ type: 'issueLabel', entity: { name: 'Example label' } })
    const issue = t.createIssue({
      teamId: team.id, title: 'Example issue', projectId: project.id, projectMilestoneId: milestone.id,
      parentId: parent.id, relations: [{ type: 'related', issueId: parent.id }], labelIds: [label.id],
    })
    t.deleteIssues({ ids: [issue.id, parent.id] })
    // Model an older app removing related records without updating its deleted issues.
    for (const id of [project.id, milestone.id, label.id]) db.remove(id)
    t.restoreIssues({ ids: [issue.id, parent.id] })
    const [saved] = t.updateIssues({ ids: [issue.id], patch: { title: 'Edited' } })
    assert.equal(saved.projectId, null)
    assert.equal(saved.projectMilestoneId, null)
    assert.deepEqual(saved.labelIds, [])
    assert.equal(saved.parentId, parent.id)
    assert.deepEqual(saved.relations, [{ type: 'related', issueId: parent.id }])
  })

  test('triage only when the team has it on', () => {
    const { t } = fresh()
    const off = t.createTeam({ name: 'Off', key: 'OFF' })
    assert.throws(() => t.createIssue({ teamId: off.id, title: 'x', stateId: stateOf(t.snapshot(), off.id, 'Triage').id }), /Triage is off/)
    const on = t.createTeam({ name: 'On', key: 'ON', triageEnabled: true })
    const i = t.createIssue({ teamId: on.id, title: 'x', triage: true })
    assert.equal(t.snapshot().states.find((s) => s.id === i.stateId).type, 'triage')
    const [accepted] = t.updateIssues({ ids: [i.id], patch: { stateId: on.defaultStateId } })
    assert.ok(accepted.triagedAt)
  })

  test('automatic cycles: upcoming cycles are made, never overlap, and unfinished issues roll over', () => {
    const { t } = fresh()
    clock = Date.parse('2026-11-18T12:00:00Z')
    const team = t.createTeam({ name: 'Eng', key: 'ENG', cyclesEnabled: true, cycleDuration: 1, upcomingCycleCount: 2 })
    const r = t.scheduleCycles({ teamId: team.id })
    const cycles = t.snapshot().cycles.sort((a, b) => a.number - b.number)
    assert.equal(r.created, 3, 'the current cycle and two ahead')
    assert.equal(cycles[0].startsAt, '2026-11-16', 'starts on Monday')
    assert.equal(t.scheduleCycles({ teamId: team.id }).created, 0, 'idempotent')
    assert.throws(() => t.save({ type: 'cycle', entity: { teamId: team.id, startsAt: '2026-11-17', endsAt: '2026-11-20' } }), /overlap/)
    const i = t.createIssue({ teamId: team.id, title: 'Carry me', cycleId: cycles[0].id })
    clock = Date.parse('2026-11-25T12:00:00Z')
    const r2 = t.scheduleCycles({ teamId: team.id })
    assert.equal(r2.rolledOver, 1)
    assert.equal(t.snapshot().issues.find((x) => x.id === i.id).cycleId, cycles[1].id)
  })

  test('the example only goes into an empty tracker and is fictional', () => {
    const { t } = fresh()
    const snap = t.addExample()
    assert.ok(snap.issues.length >= 5 && snap.projects.length === 2 && snap.initiatives.length === 1)
    assert.ok(snap.users.every((u) => !u.email), 'no addresses')
    assert.throws(() => t.addExample(), /empty tracker/)
  })

  test('views keep only known filters and display options', () => {
    const { t } = fresh()
    const v = t.save({ type: 'customView', entity: { name: 'Mine', filters: { priorities: [1, 2], nonsense: ['x'] }, display: { layout: 'board', groupBy: 'assignee' } } })
    assert.deepEqual(v.filters, { priorities: [1, 2] })
    assert.equal(v.display.layout, 'board')
    assert.throws(() => t.save({ type: 'customView', entity: { name: 'Bad', display: { layout: 'gantt' } } }), /layout/)
  })
})
