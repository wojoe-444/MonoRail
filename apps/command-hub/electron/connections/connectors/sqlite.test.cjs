const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { DatabaseSync } = require('node:sqlite')
const connector = require('./sqlite.cjs')

test('SQLite connection checks existing databases without creating or modifying them', async (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'monorail-sqlite-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  const file = path.join(dir, 'test.db')
  const db = new DatabaseSync(file)
  db.exec('CREATE TABLE example (id INTEGER)')
  db.close()
  const before = fs.readFileSync(file)
  const result = await connector.status({ values: { file } })
  assert.equal(result.state, 'ok')
  assert.match(result.summary, /1 table/)
  assert.deepEqual(fs.readFileSync(file), before)
  const missing = path.join(dir, 'missing.db')
  assert.equal((await connector.status({ values: { file: missing } })).state, 'error')
  assert.equal(fs.existsSync(missing), false)
  const invalid = path.join(dir, 'invalid.db')
  fs.writeFileSync(invalid, 'not a database')
  assert.equal((await connector.status({ values: { file: invalid } })).state, 'error')
  assert.throws(() => connector.validate({ values: { file: 'relative.db' } }), /full path/)
})
