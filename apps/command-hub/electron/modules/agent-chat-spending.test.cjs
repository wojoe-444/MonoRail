const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

const spending = require('./agent-chat-spending.cjs')

const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'spending-'))
const NOON = new Date(2026, 10, 11, 12, 0, 0).getTime()
const on = (extra = {}) => ({ enabled: true, dailyUsd: 10, monthlyUsd: 100, warnAt: 80, onLimit: 'stop', ...extra })

test('off by default: no file is read into existence, nothing is counted, turns run', () => {
  const dir = tmp()
  assert.equal(spending.getStatus(dir, NOON).state, 'off')
  spending.checkBeforeTurn(dir, NOON)
  assert.equal(spending.record(dir, 5, NOON), false)
  assert.equal(fs.existsSync(path.join(dir, spending.FILE)), false)
})

test('counts spend while on and warns at the chosen level', () => {
  const dir = tmp()
  spending.saveSettings(dir, on(), NOON)
  assert.equal(spending.record(dir, 4, NOON), true)
  assert.equal(spending.getStatus(dir, NOON).state, 'ok')
  spending.record(dir, 4.5, NOON)
  const st = spending.getStatus(dir, NOON)
  assert.equal(st.state, 'warn')
  assert.equal(st.period, 'day')
  assert.equal(st.daily.spent, 8.5)
  assert.equal(st.monthly.spent, 8.5)
  spending.checkBeforeTurn(dir, NOON) // a warning never stops a turn
})

test('stops new turns at the limit; allow one more lets exactly one through', () => {
  const dir = tmp()
  spending.saveSettings(dir, on(), NOON)
  spending.record(dir, 10.2, NOON)
  const st = spending.getStatus(dir, NOON)
  assert.equal(st.state, 'reached')
  assert.equal(st.blocked, true)
  assert.equal(st.resetsAt, new Date(2026, 10, 12).getTime())
  assert.throws(() => spending.checkBeforeTurn(dir, NOON), (e) => e.code === 'spending-limit' && /Today's spending limit/.test(e.message))
  spending.allowOneMore(dir, NOON)
  assert.equal(spending.getStatus(dir, NOON).blocked, false)
  spending.checkBeforeTurn(dir, NOON)
  assert.throws(() => spending.checkBeforeTurn(dir, NOON), /paused/)
})

test('"Only warn" never stops a turn', () => {
  const dir = tmp()
  spending.saveSettings(dir, on({ onLimit: 'warn' }), NOON)
  spending.record(dir, 50, NOON)
  assert.equal(spending.getStatus(dir, NOON).state, 'reached')
  assert.equal(spending.getStatus(dir, NOON).blocked, false)
  spending.checkBeforeTurn(dir, NOON)
})

test('day resets at midnight, month on the 1st; the month limit wins', () => {
  const dir = tmp()
  spending.saveSettings(dir, on({ dailyUsd: 10, monthlyUsd: 15 }), NOON)
  spending.record(dir, 9, NOON - 86_400_000)
  spending.record(dir, 7, NOON)
  const st = spending.getStatus(dir, NOON)
  assert.equal(st.daily.state, 'ok')
  assert.equal(st.state, 'reached')
  assert.equal(st.period, 'month')
  assert.throws(() => spending.checkBeforeTurn(dir, NOON), /This month's spending limit/)
  const december = new Date(2026, 11, 1, 9).getTime()
  assert.equal(spending.getStatus(dir, december).state, 'ok')
  assert.equal(spending.getStatus(dir, december).monthly.spent, 0)
})

test('empty limits mean none; bad values are refused', () => {
  const dir = tmp()
  const st = spending.saveSettings(dir, { enabled: true, dailyUsd: '', monthlyUsd: null }, NOON)
  assert.equal(st.daily.limit, null)
  spending.record(dir, 1000, NOON)
  assert.equal(spending.getStatus(dir, NOON).state, 'ok')
  assert.throws(() => spending.saveSettings(dir, on({ dailyUsd: -1 }), NOON), /above 0/)
  assert.throws(() => spending.saveSettings(dir, on({ dailyUsd: 'lots' }), NOON), /above 0/)
  assert.equal(spending.saveSettings(dir, on({ warnAt: 33, onLimit: 'explode' }), NOON).settings.warnAt, 80)
})

test('a damaged file is never written over, stops turns with a fix, and only reset replaces it', () => {
  const dir = tmp()
  fs.writeFileSync(path.join(dir, spending.FILE), '{nope')
  assert.equal(spending.getStatus(dir, NOON).state, 'damaged')
  assert.throws(() => spending.checkBeforeTurn(dir, NOON), (e) => e.code === 'spending-limit' && /Reset it in Settings/.test(e.message))
  assert.equal(spending.record(dir, 3, NOON), false)
  assert.throws(() => spending.saveSettings(dir, on(), NOON), /damaged/)
  assert.equal(fs.readFileSync(path.join(dir, spending.FILE), 'utf8'), '{nope')
  assert.equal(spending.reset(dir, NOON).state, 'off')
  spending.checkBeforeTurn(dir, NOON)
})

test('the file holds settings and day totals only, and old days are pruned', () => {
  const dir = tmp()
  spending.saveSettings(dir, on(), NOON)
  spending.record(dir, 2, NOON - 100 * 86_400_000)
  spending.record(dir, 1, NOON)
  const raw = JSON.parse(fs.readFileSync(path.join(dir, spending.FILE), 'utf8'))
  assert.deepEqual(Object.keys(raw).sort(), ['allowOnce', 'days', 'format', 'settings'])
  assert.deepEqual(Object.keys(raw.days), ['2026-11-11'])
  assert.equal(fs.existsSync(path.join(dir, spending.LOCK_FILE)), false)
})

test('a stale lock file is broken', () => {
  const dir = tmp()
  spending.saveSettings(dir, on(), NOON)
  const lock = path.join(dir, spending.LOCK_FILE)
  fs.writeFileSync(lock, '{}')
  const old = new Date(Date.now() - 60_000)
  fs.utimesSync(lock, old, old)
  assert.equal(spending.record(dir, 1, NOON), true)
})
